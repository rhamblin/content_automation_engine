#!/usr/bin/env bash
set -e

psql \
  --username "$POSTGRES_USER" \
  --dbname   "$POSTGRES_DB" <<-EOSQL
  GRANT USAGE ON SCHEMA analytics TO ${ANALYTICS_DB_USER};
  GRANT SELECT ON ALL TABLES IN SCHEMA analytics TO ${ANALYTICS_DB_USER};
  ALTER DEFAULT PRIVILEGES IN SCHEMA analytics GRANT SELECT ON TABLES TO ${ANALYTICS_DB_USER};
  
  GRANT USAGE ON SCHEMA niches TO ${APP_DB_USER};
  GRANT SELECT, INSERT, UPDATE, DELETE ON ALL TABLES IN SCHEMA niches TO ${APP_DB_USER};
  ALTER DEFAULT PRIVILEGES IN SCHEMA niches GRANT SELECT, INSERT, UPDATE, DELETE ON TABLES TO ${APP_DB_USER};

  GRANT USAGE ON SCHEMA pins TO ${APP_DB_USER};
  GRANT SELECT, INSERT, UPDATE, DELETE ON ALL TABLES IN SCHEMA pins TO ${APP_DB_USER};
  ALTER DEFAULT PRIVILEGES IN SCHEMA pins GRANT SELECT, INSERT, UPDATE, DELETE ON TABLES TO ${APP_DB_USER};

EOSQL
