#!/usr/bin/env bash
set -e

psql \
  --username "$POSTGRES_USER" \
  --dbname   "$POSTGRES_DB" <<-EOSQL
  GRANT USAGE ON SCHEMA analytics TO ${ANALYTICS_DB_USER};
  GRANT SELECT ON ALL TABLES IN SCHEMA analytics TO ${ANALYTICS_DB_USER};
  ALTER DEFAULT PRIVILEGES IN SCHEMA analytics
    GRANT SELECT ON TABLES TO ${ANALYTICS_DB_USER};

  GRANT USAGE ON SCHEMA analytics TO ${APP_DB_USER};
  GRANT SELECT ON ALL TABLES IN SCHEMA analytics TO ${APP_DB_USER};
  ALTER DEFAULT PRIVILEGES IN SCHEMA analytics
    GRANT SELECT ON TABLES TO ${APP_DB_USER};

  -- app user (read/write) on domain data
  GRANT USAGE ON SCHEMA niches TO ${APP_DB_USER};
  GRANT SELECT, INSERT, UPDATE, DELETE ON ALL TABLES IN SCHEMA niches TO ${APP_DB_USER};
  ALTER DEFAULT PRIVILEGES IN SCHEMA niches
    GRANT SELECT, INSERT, UPDATE, DELETE ON TABLES TO ${APP_DB_USER};

  -- app user on identity
  GRANT USAGE ON SCHEMA identity TO ${APP_DB_USER};
  GRANT SELECT, INSERT, UPDATE, DELETE ON ALL TABLES IN SCHEMA identity TO ${APP_DB_USER};
  ALTER DEFAULT PRIVILEGES IN SCHEMA identity
    GRANT SELECT, INSERT, UPDATE, DELETE ON TABLES TO ${APP_DB_USER};

  -- app user on integration_profiles (public schema)
  GRANT USAGE ON SCHEMA public TO ${APP_DB_USER};
  GRANT SELECT, INSERT, UPDATE, DELETE ON TABLE integration_profiles TO ${APP_DB_USER};
  ALTER DEFAULT PRIVILEGES IN SCHEMA public
    GRANT SELECT, INSERT, UPDATE, DELETE ON TABLES TO ${APP_DB_USER};

  -- app user on posts
  GRANT USAGE ON SCHEMA posts TO ${APP_DB_USER};
  GRANT SELECT, INSERT, UPDATE, DELETE ON ALL TABLES IN SCHEMA posts TO ${APP_DB_USER};
  ALTER DEFAULT PRIVILEGES IN SCHEMA posts
    GRANT SELECT, INSERT, UPDATE, DELETE ON TABLES TO ${APP_DB_USER};
EOSQL